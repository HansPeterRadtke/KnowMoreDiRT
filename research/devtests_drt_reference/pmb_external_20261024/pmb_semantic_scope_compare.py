"""Published human-corrected PMB 3.0 semantic gold vs REAL model DRS output.

Model output from RikVN/Neural_DRS pinned upstream revision, NOT generated by
KnowMoreDiRT in this run. Only a tiny phenomenon (presence of NEGATION scope)
is evaluated; this cannot imply full logical validity or correct discourse boxes.
Comparison is to raw source regex (cheap lexical baseline) on same sentences.
No source/ground-truth rewriting or gold-derived rule training.
"""
from pathlib import Path
import hashlib,json,re,collections
HERE=Path(__file__).resolve().parent
GOLD=Path('/data/tmp/kmd-pmb-eval-20261024/data/pmb-3.0.0/gold/test.txt')
RAW=Path('/data/tmp/kmd-pmb-eval-20261024/data/pmb-3.0.0/gold/test.txt.raw')
PRED=Path('/data/tmp/kmd-pmb-reference-20261024/output/pmb-3.0.0/en/test/bert_char_1enc/output1.txt')
OUT=HERE/'pmb_semantic_scope_results_20261024.json'
SOURCE_REVISIONS={'gold':'190838f9adea2af616eb76156d2e66c8565a6c6e','pred':'81bcb26dfcc08f0da999cc7beaa2952f8820860c'}

def groups(path):
 t=path.read_text(encoding='utf-8')
 return [g for g in re.split(r'\n\s*\n',t.strip()) if g.strip()]

def has_scope(block,marker):
 # DRS operator line, not arbitrary comment or lexical text.
 return any(len(parts:=line.split())>=3 and parts[1]==marker
   for raw in block.splitlines() if (line:=raw.strip()) and not line.startswith('%'))

def confusion(rows,key):
 tp=sum(x['gold'] and x[key] for x in rows)
 fn=sum(x['gold'] and not x[key] for x in rows)
 fp=sum(not x['gold'] and x[key] for x in rows)
 tn=sum(not x['gold'] and not x[key] for x in rows)
 precision=tp/(tp+fp) if tp+fp else None
 recall=tp/(tp+fn) if tp+fn else None
 f1=2*tp/(2*tp+fp+fn) if 2*tp+fp+fn else None
 return {'tp':tp,'fp':fp,'fn':fn,'tn':tn,'precision':precision,'recall':recall,'f1':f1}

def main():
 if OUT.exists():raise SystemExit('existing results: refusing repeat')
 names={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in (GOLD,RAW,PRED)}
 golds=groups(GOLD);preds=groups(PRED);sents=RAW.read_text().splitlines()
 assert len(golds)==len(preds)==len(sents),{'gold':len(golds),'pred':len(preds),'raw':len(sents)}
 rows=[]
 for i,(sent,gold,pred) in enumerate(zip(sents,golds,preds)):
  expected=has_scope(gold,'NEGATION')
  neural=has_scope(pred,'NEGATION')
  lexical=bool(re.search(r"\b(no|not|never|nothing|nobody|neither|none|without|can't|cannot|won't|didn't|doesn't|don't|isn't|aren't|wasn't|weren't|shouldn't|couldn't|wouldn't|mustn't|hasn't|haven't|hadn't)\b|n['’]t\b",sent.casefold()))
  rows.append({'index':i,'sentence_sha256':hashlib.sha256(sent.encode()).hexdigest(),'gold_negative':expected,'model_negative':neural,'lexical_negative':lexical,'raw_source_sentence':sent})
 # Gold presence in result is diagnostic, not used to change regex threshold.
 folded=[{'gold':r['gold_negative'],'neural':r['model_negative'],'lexical':r['lexical_negative']} for r in rows]
 out={'protocol':'Untuned original lexical negation regex versus published automatically parsed DRS operator; independent PMB 3.0 gold. Exact same 898 original natural sentences.','source_revisions':SOURCE_REVISIONS,'source_sha256':names,'total':len(rows),'gold_negation_count':sum(x['gold'] for x in folded),'models':{'published_neural_DRS':confusion(folded,'neural'),'lexical_unscoped_negation':confusion(folded,'lexical')},'model_disagree_on_gold_negation':[x for x in rows if x['gold_negative'] and not x['model_negative']][:30],
 'lexical_disagree_on_gold_negation':[x for x in rows if x['gold_negative'] and not x['lexical_negative']][:30],
 'gold_scope_operator_counts':dict(collections.Counter(x.split()[1] for g in golds for x in g.splitlines() if x and not x.startswith('%') and len(x.split())>=3 and x.split()[1] in ('NEGATION','IMP','OR','NEC','POS','PRP'))),
 'limits':['A model-extracted DRS from a specialized published model; not KMD Qwen and not a comparison of full DRS against end-to-end provenance-neighbor retrieval.','Only detection of the existence of a NEGATION box; ignores which proposition is negated and whether source context correctly applies.','PMB contains short utterances, not Wikipedia multi-document research, dreams or cross-document identity.','An operator F1 score is NOT a knowledge discovery or falsification rate; source paper and gold annotations are linguistic, not verified physical facts.'],
 'source_url_predictions':'https://github.com/RikVN/Neural_DRS','source_url_gold':'https://github.com/RikVN/DRS_parsing'}
 OUT.write_text(json.dumps(out,indent=2,ensure_ascii=False)+'\n')
 print('CASE_COUNT',len(rows),'NEG_GOLD',out['gold_negation_count']);print('DRS',out['models']['published_neural_DRS']);print('LEXICAL',out['models']['lexical_unscoped_negation']);print('OTHER_OPERATOR_COUNTS',out['gold_scope_operator_counts'])
if __name__=='__main__':main()
